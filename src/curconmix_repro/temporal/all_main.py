def _extract_float_from_any(x: Any) -> Optional[float]:
    """base_train의 다양한 반환 타입에서 float 스칼라를 추출합니다."""
    if x is None:
        return None
    if isinstance(x, (float, int)):
        return float(x)
    if isinstance(x, np.ndarray):
        if x.size == 1:
            return float(x.item())
        try:
            return float(np.nanmean(x))
        except Exception:
            return None
    if torch.is_tensor(x):
        try:
            return float(x.detach().cpu().item())
        except Exception:
            try:
                return float(x.mean().detach().cpu().item())
            except Exception:
                return None
    if isinstance(x, dict):
        # 우선 순위가 높은 키부터 확인
        candidate_keys = ["mAP", "map", "score", "best_score", "metric"]
        for k in candidate_keys:
            if k in x:
                return _extract_float_from_any(x[k])
    if isinstance(x, (tuple, list)) and len(x) > 0:
        return _extract_float_from_any(x[0])
    try:
        return float(x)
    except Exception:
        return None


def fmt4(x: Optional[float]) -> str:
    """float 값을 소수점 4자리 문자열로 포맷팅합니다."""
    if x is None or not np.isfinite(x):
        return "nan"
    return f"{x:.4f}"


def run_single_fold(
    args,
    fold: int,
    mr2_hparams: dict,
    checkpoint_dir: str,
    device: torch.device,
    wandb_run=None,
) -> Optional[float]:
    """단일 fold에 대한 훈련 및 검증을 실행합니다."""
    logging.info("=" * 20 + f" Starting Fold {fold} " + "=" * 20)

    num_classes = 131 if args.dataset in ["cholect45", "cholect50"] else 266

    split = load_training_split(args.training_split, args.dataset)
    config = {"dataset": args.dataset, "model_name": args.name, "dim": args.dim}
    load_training_order(Path(args.procedure_order), config, split)
    audit = validate_training_features(
        args.training_feature_manifest,
        config,
        FEATURE_ROOT,
        LABEL_ROOT,
        split,
        fold=fold,
    )
    if getattr(args, "training_feature_manifest_sha256", "") not in (
        "",
        audit["manifest_sha256"],
    ):
        raise ValueError(
            "Training feature manifest changed between preflight and training"
        )
    args.training_split_sha256 = split_digest(split)
    args.training_feature_manifest_sha256 = audit["manifest_sha256"]
    # Only fitting and independent inner-validation procedures are loaded.
    train_ds = VideoDataset(
        args.dataset, args.name, "train", fold, training_split=split
    )
    val_ds = VideoDataset(
        args.dataset, args.name, "inner_validation", fold, training_split=split
    )
    train_loader = DataLoader(
        train_ds,
        batch_size=args.batch_size,
        shuffle=True,
        drop_last=False,
        num_workers=args.num_workers,
        pin_memory=True,
    )
    val_loader = DataLoader(
        val_ds,
        batch_size=args.batch_size,
        shuffle=False,
        drop_last=False,
        num_workers=args.num_workers,
        pin_memory=True,
    )

    # 모델 생성
    if args.model_type == "mr1":
        model = MultiResTemporalModel(
            embed_dim=args.dim,
            num_classes=num_classes,
            ks=tuple(map(int, args.ks.split(","))),
        )
    else:
        model = MultiResTemporalModel2(
            embed_dim=args.dim, num_classes=num_classes, **mr2_hparams
        )

    try:
        best_perf_raw = base_train(
            args,
            model,
            train_loader,
            val_loader,
            device,
            save_dir=checkpoint_dir,  # 메인 함수에서 생성된 공통 체크포인트 폴더 전달
            fold_num=fold,  # 체크포인트 파일명에 사용할 fold 번호 전달
            debug=True,
            wandb_run=wandb_run,
        )
    except Exception as e:
        logging.exception(f"[Fold {fold}] base_train() execution failed.")
        if wandb_run is not None:
            wandb_run.log(
                {
                    "phase": "mrtt_train",
                    "fold": fold,
                    "fold_error": str(e),
                }
            )
        raise

    # 결과 정규화 및 로깅
    best_perf = _extract_float_from_any(best_perf_raw)
    if best_perf is None:
        logging.warning(
            f"[Fold {fold}] Could not extract metric from base_train return: {best_perf_raw}"
        )
    else:
        logging.info(f"[Fold {fold}] Best performance: {best_perf:.6f}")
    return best_perf


def main():
    """메인 실행 함수"""
    setup_logger()
    parent_parser = argparse.ArgumentParser("Temporal Training Setup", add_help=False)
    parser = argparse.ArgumentParser(
        parents=[parent_parser, get_args_parser()], add_help=True
    )
    args = parser.parse_args()
    split = load_training_split(args.training_split, args.dataset)
    procedure_order = load_training_order(
        Path(args.procedure_order),
        {"dataset": args.dataset, "model_name": args.name},
        split,
    )
    args.procedure_order_sha256 = order_sha256(procedure_order)
    digest = file_sha256(args.training_feature_manifest)
    if args.training_feature_manifest_sha256 not in ("", digest):
        raise ValueError("Training feature manifest hash mismatch")
    args.training_feature_manifest_sha256 = digest
    set_seed(42)

    # --- 장치 설정 ---
    if args.device:
        device = torch.device(args.device)
    else:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    logging.info(f"Using device: {device}")
    if device.type == "cuda":
        torch.cuda.set_device(device)

    os.environ["CUDA_DEVICE_ORDER"] = "PCI_BUS_ID"

    # MR2 모델 하이퍼파라미터를 args로부터 구성
    mr2_hparams = {
        "ks": tuple(map(int, args.ks.split(","))),
        "fusion": args.fusion,
        "use_spatial_norm": args.use_spatial_norm,
        "spatial_dropout": args.spatial_dropout,
        "ks_weights": args.ks_weights,
        "temporal_cfg": {
            "nhead": 4,
            "num_layers": 3,
            "dim_feedforward": 2048,
            "dropout": 0.1,
        },
    }

    tag_tokens = [
        part.strip() for part in str(args.wandb_tags).split(",") if part.strip()
    ]
    tag_tokens.extend([args.dataset, args.model_type, "mrtt", "fix20260328"])

    # --- CSV 및 체크포인트 경로 생성 ---
    os.makedirs(args.results_dir, exist_ok=True)
    if args.results_filename:
        filename = args.results_filename
        if not filename.lower().endswith(".csv"):
            filename += ".csv"
    else:
        date_str = datetime.datetime.now().strftime("%Y%m%d")
        hparam_str = (
            f"ks{''.join(map(str, mr2_hparams['ks']))}_fus-{mr2_hparams['fusion']}"
            if args.model_type == "mr2"
            else "default"
        )
        filename = f"{date_str}_{args.model_type}_{hparam_str}_{args.name}.csv"

    results_file_path = os.path.join(args.results_dir, filename)

    ckpt_folder_name = os.path.splitext(filename)[0]
    checkpoint_dir = os.path.join(args.save_root, ckpt_folder_name)
    os.makedirs(checkpoint_dir, exist_ok=True)
    logging.info(f"Checkpoints and logs will be saved in: {checkpoint_dir}")

    wandb_run = init_safe_wandb(
        {
            **vars(args),
            "mr2_hparams": mr2_hparams,
            "checkpoint_dir": checkpoint_dir,
            "results_file_path": results_file_path,
        },
        enabled=bool(args.wandb_log),
        project=args.wandb_project,
        entity=args.wandb_entity,
        mode=args.wandb_mode,
        group=args.wandb_group,
        tags=tag_tokens,
        run_name=os.path.splitext(filename)[0],
        wandb_dir=args.wandb_dir,
    )
    wandb_session_path = os.path.join(checkpoint_dir, "wandb_session.json")
    wandb_run.write_session(wandb_session_path)

    # --- 5-Fold 훈련 실행 및 결과 수집 ---
    fold_results_data, perf_values = [], []
    for fold in range(args.folds):
        perf = run_single_fold(
            args, fold, mr2_hparams, checkpoint_dir, device, wandb_run=wandb_run
        )
        perf_values.append(perf)

        result = {
            "timestamp": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "model_name": args.name,
            "model_type": args.model_type,
            "dataset": args.dataset,
            "fold": fold,
            "dim": args.dim,
            "learning_rate": args.learning_rate,
            "epochs": args.epochs,
            "batch_size": args.batch_size,
            "best_inner_validation_AP": perf,
        }
        if args.model_type == "mr2":
            result.update(
                {
                    "ks": str(mr2_hparams["ks"]),
                    "fusion": mr2_hparams["fusion"],
                    "use_spatial_norm": mr2_hparams["use_spatial_norm"],
                    "spatial_dropout": mr2_hparams["spatial_dropout"],
                    "ks_weights": mr2_hparams["ks_weights"],
                }
            )
        fold_results_data.append(result)

    results_df = pd.DataFrame(fold_results_data)

    finite_perfs = [p for p in perf_values if p is not None and np.isfinite(p)]
    avg = float(np.mean(finite_perfs)) if finite_perfs else np.nan
    std = float(np.std(finite_perfs)) if finite_perfs else np.nan

    summary_data = {
        "fold": [f"avg_over_{len(finite_perfs)}_folds"],
        "best_inner_validation_AP": [f"{fmt4(avg)} ± {fmt4(std)}"],
    }
    summary_df = pd.DataFrame(summary_data)

    final_df = pd.concat([results_df, summary_df], ignore_index=True)
    final_df.to_csv(results_file_path, index=False, encoding="utf-8-sig")

    wandb_run.update_summary(
        {
            "phase": "mrtt_train",
            "completed_folds": len(finite_perfs),
            "final_mean_valid_mAP": avg,
            "final_std_valid_mAP": std,
            "checkpoint_dir": checkpoint_dir,
            "results_csv": results_file_path,
        }
    )
    wandb_run.finish()

    logging.info("=" * 60)
    logging.info("Training finished for all folds.")
    logging.info(f"Results saved to: {results_file_path}")
    logging.info("=" * 60)


if __name__ == "__main__":
    main()
